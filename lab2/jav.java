import java.util.Random;

/**
 * Главный класс программы, генерирующий случайную битовую последовательность.
 * При запуске программы создается генератор случайных чисел, затем
 * генерируется массив из 128 битов (0 или 1), который выводится на консоль.
 * Также отображается длина полученной последовательности.
 */
public class Main {
    /**
     * Точка входа в программу.
     * Создает объект генератора случайных чисел, формирует массив из 128 элементов,
     * заполняет его случайными битами (0 или 1), и выводит результат в консоль.
     *
     * @param args аргументы командной строки (не используются)
     */
    public static void main(String[] args) {
        Random random = new Random();
        int[] bitSequence = new int[128];

        // Генерация битовой последовательности
        for (int i = 0; i < bitSequence.length; i++) {
            bitSequence[i] = random.nextInt(2); // Генерация 0 или 1
        }

        // Форматированный вывод результатов
        System.out.println("Сгенерированная последовательность:");
        for (int bit : bitSequence) {
            System.out.print(bit);
        }

        // Вывод длины последовательности
        System.out.println("\n\nДлина последовательности: " + bitSequence.length + " бит");
    }
}
